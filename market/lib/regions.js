// '아라일동', '제주시 아라동', '애월' 같은 말에서 동네를 찾는다
const stem = (s) => s.replace(/\d/g, '').replace(/[읍면동]$/, '');
function findRegion(text) {
  const t = String(text || '').replace(/\s+/g, ''); if (!t) return null;
  return REGIONS.find((r) => t.includes(r.short)) || REGIONS.find((r) => { const k = stem(r.short); return k.length >= 2 && t.includes(k); }) || REGIONS.find((r) => r.short === t + '동') || null;
}
// 같은 동네의 점들이 겹치지 않게 id로 조금씩 흩는다 (항상 같은 자리)
function jitter(id, lat, lng) {
  let h = 0; for (const ch of String(id)) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  const a = (h % 360) * Math.PI / 180, d = 0.0025 + ((h >> 9) % 100) / 100 * 0.004;
  return { lat: +(lat + Math.sin(a) * d).toFixed(5), lng: +(lng + Math.cos(a) * d * 1.2).toFixed(5) };
}
